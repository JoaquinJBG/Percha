import type { TiempoHoy } from '../../tiempo/tipos.ts'
import type { PrendaReglas } from './tipos.ts'

let siguiente = 0

export function prenda(cambios: Partial<PrendaReglas> = {}): PrendaReglas {
  siguiente += 1
  return {
    id: `p${String(siguiente).padStart(3, '0')}`,
    categoria: 'superior',
    subcategoria: 'camiseta',
    colores: ['blanco'],
    estampado: 'liso',
    estilos: ['casual'],
    abrigo: 2,
    formalidad: 2,
    ocasiones: [],
    temporadas: [],
    notas: '',
    ...cambios,
  }
}

/** Un día con la sensación térmica media que se pida (mínima y máxima a ±3 °C). */
export function tiempo(
  sensacion: number,
  cambios: { precipitacion?: 'lluvia' | 'nieve'; fecha?: string; latitud?: number } = {},
): TiempoHoy {
  const fecha = cambios.fecha ?? '2026-11-03'
  const rango = { actual: sensacion, minima: sensacion - 3, maxima: sensacion + 3 }
  return {
    sitio: { nombre: 'Madrid', latitud: cambios.latitud ?? 40.4, longitud: -3.7 },
    zonaHoraria: 'Europe/Madrid',
    fecha,
    hora: `${fecha}T09:00`,
    temperatura: rango,
    sensacion: rango,
    lluvia: {
      probabilidad: cambios.precipitacion ? 90 : 0,
      cantidad: cambios.precipitacion ? 5 : 0,
    },
    viento: { actual: 5, maximo: 10 },
    codigo: cambios.precipitacion === 'nieve' ? 73 : cambios.precipitacion ? 61 : 1,
    clima: {
      termico:
        sensacion < 10 ? 'frio' : sensacion < 16 ? 'fresco' : sensacion < 24 ? 'templado' : 'calor',
      precipitacion: cambios.precipitacion ?? null,
      viento: false,
    },
    resumen: '',
  }
}

